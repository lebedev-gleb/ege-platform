// Перемешивание Фишера–Йетса: каждый порядок равновероятен.
// Популярный трюк sort(() => Math.random() - 0.5) перемешивает нечестно —
// одни перестановки выпадают чаще других, поэтому так делать не стоит.
//
// <T> — дженерик: функция работает с массивом ЛЮБОГО типа.
// Сегодня перемешиваем вопросы и задачи, завтра — что угодно.
export function shuffle<T>(array: T[]): T[] {
  const result = [...array]; // копия — исходный массив не трогаем
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}